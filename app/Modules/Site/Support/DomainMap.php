<?php

declare(strict_types=1);

namespace CMS\Modules\Site\Support;

use RuntimeException;

/**
 * Compiled host -> site id map stored as a PHP file.
 *
 * This is the cache-first half of tenant resolution: a cached public request
 * must be able to answer "which site is this host?" with a single opcache hit
 * and zero database queries. The file is regenerated whenever a domain mapping
 * changes, never on read.
 *
 * A PHP file (rather than JSON) is used deliberately so opcache can hold the
 * parsed array in shared memory on standard shared hosting.
 */
final class DomainMap
{
    private const FILENAME = 'domain-map.php';

    /** @var array<string, int>|null In-process memo for this request. */
    private ?array $memo = null;

    public function __construct(private readonly string $directory)
    {
    }

    public function path(): string
    {
        return $this->directory . DIRECTORY_SEPARATOR . self::FILENAME;
    }

    /**
     * Load the compiled map.
     *
     * Returns an empty map when the file is missing: an absent map means
     * "nothing compiled yet", and resolution falls through to the database.
     * That is not a fallback to site 1 — it is a fallback to the source of
     * truth.
     *
     * @return array<string, int>
     */
    public function load(): array
    {
        if ($this->memo !== null) {
            return $this->memo;
        }

        $path = $this->path();

        if (!is_file($path) || !is_readable($path)) {
            return $this->memo = [];
        }

        /** @var mixed $loaded */
        $loaded = require $path;

        if (!is_array($loaded)) {
            return $this->memo = [];
        }

        $map = [];

        foreach ($loaded as $host => $siteId) {
            if (is_string($host) && $host !== '' && is_int($siteId) && $siteId > 0) {
                $map[$host] = $siteId;
            }
        }

        return $this->memo = $map;
    }

    /**
     * Look up a single normalized host.
     */
    public function siteIdFor(string $host): ?int
    {
        return $this->load()[$host] ?? null;
    }

    /**
     * Atomically write a new compiled map.
     *
     * @param array<string, int> $map
     *
     * @return int number of host mappings written
     */
    public function compile(array $map): int
    {
        ksort($map);

        $contents = $this->render($map);
        $path = $this->path();
        $directory = dirname($path);

        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw new RuntimeException('Unable to create domain-map directory: ' . $directory);
        }

        // Write to a sibling temp file then rename, so a concurrent reader
        // never sees a half-written map.
        $temp = $path . '.' . bin2hex(random_bytes(6)) . '.tmp';

        if (file_put_contents($temp, $contents) === false) {
            throw new RuntimeException('Unable to write domain map temp file.');
        }

        @chmod($temp, 0644);

        if (!rename($temp, $path)) {
            @unlink($temp);

            throw new RuntimeException('Unable to replace domain map file.');
        }

        // Burn the opcache entry for the old file so the next request parses
        // the new one, and drop this request's memo.
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }

        $this->memo = $map;

        return count($map);
    }

    /**
     * Forget the in-process memo (the file itself is left in place).
     */
    public function flush(): void
    {
        $this->memo = null;
    }

    public function delete(): void
    {
        $path = $this->path();

        if (is_file($path)) {
            @unlink($path);
        }

        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }

        $this->memo = null;
    }

    /**
     * @param array<string, int> $map
     */
    private function render(array $map): string
    {
        return "<?php\n\n"
            . "declare(strict_types=1);\n\n"
            . "/*\n"
            . " * Compiled tenant domain map. DO NOT EDIT.\n"
            . " *\n"
            . " * Generated by " . self::class . "::compile().\n"
            . " * Regenerated automatically whenever a domain mapping changes.\n"
            . " */\n\n"
            . 'return ' . var_export($map, true) . ";\n";
    }
}
